FROM universities university
LEFT JOIN countries country ON country.id = university.country_id
WHERE (country.code = 'MY' OR lower(university.country) = 'malaysia')
  AND NOT EXISTS (
      SELECT 1 FROM search_sync_jobs existing
      WHERE existing.university_id = university.id
        AND existing.status IN ('PENDING', 'PROCESSING')
  );

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM programmes programme
        JOIN universities university ON university.id = programme.university_id
        LEFT JOIN countries country ON country.id = university.country_id
        WHERE (country.code = 'MY' OR lower(university.country) = 'malaysia')
          AND programme.status = 'PUBLISHED'
          AND EXISTS (
              SELECT 1 FROM verified_malaysia_programme_taxonomy verified
              WHERE verified.programme_code = programme.programme_code
                AND verified.university_slug = university.slug
          )
          AND (
              programme.source_type <> 'official'
              OR programme.source_url IS NULL
              OR programme.source_checked_at IS NULL
              OR NULLIF(btrim(programme.name_zh), '') IS NULL
              OR NULLIF(btrim(programme.name_en), '') IS NULL
              OR programme.study_level_id IS NULL
              OR programme.subject_category_id IS NULL
          )
    ) THEN
        RAISE EXCEPTION 'A published Malaysian programme is not fully verified';
    END IF;
END $$;
