CREATE TABLE account_management_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL REFERENCES user_accounts(id),
    target_user_id BIGINT NOT NULL REFERENCES user_accounts(id),
    actor_name VARCHAR(100) NOT NULL,
    target_name VARCHAR(100) NOT NULL,
    action VARCHAR(20) NOT NULL CHECK (action IN ('ROLE', 'STATUS')),
    old_role VARCHAR(32) NOT NULL,
    new_role VARCHAR(32) NOT NULL,
    old_status VARCHAR(32) NOT NULL,
    new_status VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_account_management_audit_target ON account_management_audit(target_user_id, id DESC);
CREATE INDEX idx_user_accounts_admin_page ON user_accounts(created_at DESC, id DESC);
