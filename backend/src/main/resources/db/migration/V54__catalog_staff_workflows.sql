-- Separate internal course code from module_data.courseCode (the school's official code).
CREATE TABLE catalog_courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code VARCHAR(64) NOT NULL UNIQUE,
    programme_id BIGINT NOT NULL REFERENCES programmes(id) ON DELETE RESTRICT,
    source_key TEXT NOT NULL,
    module_data JSONB NOT NULL CHECK (jsonb_typeof(module_data)='object'),
    source_type VARCHAR(20) NOT NULL DEFAULT 'third_party'
        CHECK (source_type IN ('official','third_party','ai_generated')),
    sort_order INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'PUBLISHED' CHECK(status IN ('PUBLISHED','ARCHIVED','DRAFT')),
    deleted_at TIMESTAMPTZ,
    previous_status VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(programme_id,source_key)
);
CREATE INDEX idx_catalog_courses_programme ON catalog_courses(programme_id,status,sort_order,id);
CREATE INDEX idx_catalog_courses_trash ON catalog_courses(deleted_at) WHERE deleted_at IS NOT NULL;

-- Official collection jobs still write the existing JSON contract. Mirror their updates;
-- preserve identifiers and recycle-bin decisions when the same official module returns.
CREATE FUNCTION mirror_catalog_course_modules() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE m JSONB; n INTEGER:=0; k TEXT; internal_code TEXT; keys TEXT[]:='{}';
BEGIN
    IF NEW.section_type <> 'CURRICULUM' OR current_setting('udajo.catalog_course_sync',true)='on' THEN RETURN NEW; END IF;
    FOR m IN SELECT value FROM jsonb_array_elements(NEW.course_modules) LOOP
        n:=n+1;
        k:=md5(lower(regexp_replace(COALESCE(NULLIF(m->>'courseCode',''),NULLIF(m->>'nameEn',''),m->>'nameZh','') ,'\s+','','g')));
        IF k=ANY(keys) THEN CONTINUE; END IF;
        keys:=array_append(keys,k);
        internal_code:='C_'||upper(replace(gen_random_uuid()::text,'-',''));
        INSERT INTO catalog_courses(course_code,programme_id,source_key,module_data,source_type,sort_order)
        VALUES(internal_code,NEW.programme_id,k,m,COALESCE(NEW.source_type,'third_party'),n)
        ON CONFLICT(programme_id,source_key) DO UPDATE SET module_data=EXCLUDED.module_data,
            sort_order=EXCLUDED.sort_order,source_type=EXCLUDED.source_type,updated_at=CURRENT_TIMESTAMP;
    END LOOP;
    UPDATE catalog_courses SET status='ARCHIVED',updated_at=CURRENT_TIMESTAMP
      WHERE programme_id=NEW.programme_id AND NOT(source_key=ANY(keys)) AND deleted_at IS NULL;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_mirror_catalog_course_modules AFTER INSERT OR UPDATE OF course_modules ON programme_detail_sections
    FOR EACH ROW EXECUTE FUNCTION mirror_catalog_course_modules();
-- Populate the management projection without altering any existing public module content.
UPDATE programme_detail_sections SET course_modules=course_modules WHERE section_type='CURRICULUM' AND jsonb_array_length(course_modules)>0;
INSERT INTO catalog_code_reservations(entity_type,code) SELECT 'COURSE',course_code FROM catalog_courses ON CONFLICT DO NOTHING;
CREATE FUNCTION reserve_catalog_course_code() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO catalog_code_reservations(entity_type,code) VALUES('COURSE',NEW.course_code) ON CONFLICT DO NOTHING;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_reserve_catalog_course_code AFTER INSERT ON catalog_courses FOR EACH ROW EXECUTE FUNCTION reserve_catalog_course_code();

