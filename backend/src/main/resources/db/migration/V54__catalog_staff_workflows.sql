-- Internal identifiers are reserved independently of live records and never reused.
CREATE TABLE catalog_code_reservations (
    entity_type VARCHAR(20) NOT NULL,
    code VARCHAR(64) NOT NULL,
    reserved_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    retired_at TIMESTAMPTZ,
    PRIMARY KEY(entity_type, code)
);
INSERT INTO catalog_code_reservations(entity_type,code)
SELECT 'UNIVERSITY',university_code FROM universities WHERE university_code IS NOT NULL
UNION ALL SELECT 'PROGRAMME',programme_code FROM programmes;

