CREATE TABLE programmes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programme_code VARCHAR(64) NOT NULL,
    university_id BIGINT NOT NULL,
    subject_category_id BIGINT NOT NULL,
    study_level_id BIGINT,
    course_mode_id BIGINT,
    slug VARCHAR(200) NOT NULL,
    name_zh VARCHAR(200),
    name_en VARCHAR(200),
    description_zh TEXT,
    description_en TEXT,
    duration_months INTEGER,
    duration_display VARCHAR(100),
    tuition_min NUMERIC(14, 2),
    tuition_max NUMERIC(14, 2),
    tuition_currency CHAR(3),
    tuition_display VARCHAR(200),
    tuition_rmb_min NUMERIC(14, 2),
    tuition_rmb_max NUMERIC(14, 2),
    exchange_rate NUMERIC(18, 8),
    exchange_rate_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP WITH TIME ZONE,

    CONSTRAINT uk_programmes_programme_code UNIQUE (programme_code),
    CONSTRAINT uk_programmes_university_slug UNIQUE (university_id, slug),
    CONSTRAINT fk_programmes_university FOREIGN KEY (university_id)
        REFERENCES universities (id) ON DELETE RESTRICT,
    CONSTRAINT fk_programmes_subject_category FOREIGN KEY (subject_category_id)
        REFERENCES subject_categories (id) ON DELETE RESTRICT,
    CONSTRAINT fk_programmes_study_level FOREIGN KEY (study_level_id)
        REFERENCES study_levels (id) ON DELETE RESTRICT,
    CONSTRAINT fk_programmes_course_mode FOREIGN KEY (course_mode_id)
        REFERENCES course_modes (id) ON DELETE RESTRICT,
    CONSTRAINT ck_programmes_code_format CHECK (
        programme_code ~ '^[A-Z][A-Z0-9_]{0,63}$'
    ),
    CONSTRAINT ck_programmes_name_present CHECK (
        NULLIF(BTRIM(name_zh), '') IS NOT NULL
        OR NULLIF(BTRIM(name_en), '') IS NOT NULL
    ),
    CONSTRAINT ck_programmes_duration_months CHECK (
        duration_months IS NULL OR duration_months > 0
    ),
    CONSTRAINT ck_programmes_tuition_min CHECK (
        tuition_min IS NULL OR tuition_min >= 0
    ),
    CONSTRAINT ck_programmes_tuition_max CHECK (
        tuition_max IS NULL OR tuition_max >= 0
    ),
    CONSTRAINT ck_programmes_tuition_range CHECK (
        tuition_min IS NULL
        OR tuition_max IS NULL
        OR tuition_min <= tuition_max
    ),
    CONSTRAINT ck_programmes_tuition_currency_format CHECK (
        tuition_currency IS NULL OR tuition_currency ~ '^[A-Z]{3}$'
    ),
    CONSTRAINT ck_programmes_tuition_currency_present CHECK (
        (tuition_min IS NULL AND tuition_max IS NULL)
        OR tuition_currency IS NOT NULL
    ),
    CONSTRAINT ck_programmes_tuition_rmb_min CHECK (
        tuition_rmb_min IS NULL OR tuition_rmb_min >= 0
    ),
    CONSTRAINT ck_programmes_tuition_rmb_max CHECK (
        tuition_rmb_max IS NULL OR tuition_rmb_max >= 0
    ),
    CONSTRAINT ck_programmes_tuition_rmb_range CHECK (
        tuition_rmb_min IS NULL
        OR tuition_rmb_max IS NULL
        OR tuition_rmb_min <= tuition_rmb_max
    ),
    CONSTRAINT ck_programmes_exchange_rate_positive CHECK (
        exchange_rate IS NULL OR exchange_rate > 0
    ),
    CONSTRAINT ck_programmes_rmb_conversion_present CHECK (
        (tuition_rmb_min IS NULL AND tuition_rmb_max IS NULL)
        OR (exchange_rate IS NOT NULL AND exchange_rate_date IS NOT NULL)
    ),
    CONSTRAINT ck_programmes_status CHECK (
        status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')
    )
);

CREATE TABLE programme_languages (
    programme_id BIGINT NOT NULL,
    language_id BIGINT NOT NULL,

    CONSTRAINT pk_programme_languages PRIMARY KEY (programme_id, language_id),
    CONSTRAINT fk_programme_languages_programme FOREIGN KEY (programme_id)
        REFERENCES programmes (id) ON DELETE CASCADE,
    CONSTRAINT fk_programme_languages_language FOREIGN KEY (language_id)
        REFERENCES languages (id) ON DELETE RESTRICT
);

CREATE TABLE programme_intakes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programme_id BIGINT NOT NULL,
    intake_date DATE,
    display_text VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_programme_intakes_programme FOREIGN KEY (programme_id)
        REFERENCES programmes (id) ON DELETE CASCADE,
    CONSTRAINT ck_programme_intakes_display_text CHECK (
        NULLIF(BTRIM(display_text), '') IS NOT NULL
    )
);

