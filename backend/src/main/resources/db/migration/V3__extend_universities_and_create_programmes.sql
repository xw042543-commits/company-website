CREATE TABLE study_levels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL,
    name_zh VARCHAR(200),
    name_en VARCHAR(200),
    sort_order INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_study_levels_code UNIQUE (code),
    CONSTRAINT ck_study_levels_code_format CHECK (
        code ~ '^[A-Z][A-Z0-9_]{0,63}$'
    ),
    CONSTRAINT ck_study_levels_name_present CHECK (
        NULLIF(BTRIM(name_zh), '') IS NOT NULL
        OR NULLIF(BTRIM(name_en), '') IS NOT NULL
    ),
    CONSTRAINT ck_study_levels_sort_order CHECK (sort_order >= 0),
    CONSTRAINT ck_study_levels_status CHECK (
        status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')
    )
);

