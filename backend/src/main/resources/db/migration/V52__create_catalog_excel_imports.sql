CREATE TABLE catalog_import_batches (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    entity_type VARCHAR(20) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    uploaded_by_user_id BIGINT NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PROCESSED',
    total_rows INTEGER NOT NULL DEFAULT 0,
    draft_rows INTEGER NOT NULL DEFAULT 0,
    exact_duplicate_rows INTEGER NOT NULL DEFAULT 0,
    possible_duplicate_rows INTEGER NOT NULL DEFAULT 0,
    conflict_rows INTEGER NOT NULL DEFAULT 0,
    invalid_rows INTEGER NOT NULL DEFAULT 0,
    published_rows INTEGER NOT NULL DEFAULT 0,
    failed_rows INTEGER NOT NULL DEFAULT 0,
    failure_reason VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_catalog_import_batches_user FOREIGN KEY (uploaded_by_user_id)
        REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT ck_catalog_import_batches_type CHECK (entity_type IN ('UNIVERSITY','PROGRAMME')),
    CONSTRAINT ck_catalog_import_batches_status CHECK (status IN ('PROCESSED','PARTIALLY_PUBLISHED','PUBLISHED','FAILED')),
    CONSTRAINT ck_catalog_import_batches_counts CHECK (
        total_rows >= 0 AND draft_rows >= 0 AND exact_duplicate_rows >= 0
        AND possible_duplicate_rows >= 0 AND conflict_rows >= 0 AND invalid_rows >= 0
        AND published_rows >= 0 AND failed_rows >= 0
    )
);

CREATE TABLE catalog_import_rows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id UUID NOT NULL,
    row_number INTEGER NOT NULL,
    entity_type VARCHAR(20) NOT NULL,
    classification VARCHAR(24) NOT NULL,
    draft_status VARCHAR(20) NOT NULL DEFAULT 'NOT_DRAFT',
    payload JSONB NOT NULL,
    normalized_key VARCHAR(1000),
    duplicate_reason VARCHAR(1000),
    matched_record_id BIGINT,
    published_record_id BIGINT,
    error_message VARCHAR(1000),
    parse_error VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_catalog_import_rows_batch FOREIGN KEY (batch_id)
        REFERENCES catalog_import_batches(id) ON DELETE CASCADE,
    CONSTRAINT uk_catalog_import_rows_batch_row UNIQUE (batch_id,row_number),
    CONSTRAINT ck_catalog_import_rows_type CHECK (entity_type IN ('UNIVERSITY','PROGRAMME')),
    CONSTRAINT ck_catalog_import_rows_classification CHECK (
        classification IN ('NEW','EXACT_DUPLICATE','POSSIBLE_DUPLICATE','CONFLICT','INVALID')
    ),
    CONSTRAINT ck_catalog_import_rows_draft_status CHECK (
        draft_status IN ('DRAFT','REMOVED','PUBLISHED','NOT_DRAFT','FAILED')
    ),
    CONSTRAINT ck_catalog_import_rows_row_number CHECK (row_number >= 2)
);

CREATE INDEX idx_catalog_import_batches_history
    ON catalog_import_batches(created_at DESC,id);
CREATE INDEX idx_catalog_import_rows_batch_classification
    ON catalog_import_rows(batch_id,classification,draft_status,row_number);

CREATE TABLE catalog_entity_aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(20) NOT NULL,
    entity_id BIGINT NOT NULL,
    alias VARCHAR(200) NOT NULL,
    normalized_alias VARCHAR(200) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_catalog_entity_aliases_type CHECK (entity_type IN ('UNIVERSITY','PROGRAMME')),
    CONSTRAINT ck_catalog_entity_aliases_value CHECK (
        NULLIF(BTRIM(alias),'') IS NOT NULL AND NULLIF(BTRIM(normalized_alias),'') IS NOT NULL
    ),
    CONSTRAINT uk_catalog_entity_aliases_target UNIQUE(entity_type,entity_id,normalized_alias)
);

CREATE INDEX idx_catalog_entity_aliases_lookup
    ON catalog_entity_aliases(entity_type,normalized_alias);
