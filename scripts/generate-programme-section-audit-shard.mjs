import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const shard = Number(process.argv[2]);
const version = Number(process.argv[3]);
if (!Number.isInteger(shard) || shard < 0 || shard > 3 || !Number.isInteger(version)) {
  throw new Error('Usage: node scripts/generate-programme-section-audit-shard.mjs <shard 0..3> <migration version>');
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(resolve(root,
  'backend/src/main/resources/db/migration/V33__enrich_published_programme_content.sql'), 'utf8');
const profileEnd = source.indexOf('), matched AS (');
if (profileEnd < 0) throw new Error('V33 content profile CTE was not found');
const profiles = source.slice(source.indexOf('WITH content_profiles('), profileEnd + 1);

const sql = `-- Generated by scripts/generate-programme-section-audit-shard.mjs.
-- Shard ${shard}/4: only published programmes whose id modulo 4 equals ${shard}.
-- Official and third-party source text is preserved. Only missing or invalid
-- ai_generated content is replaced with clearly labelled editorial guidance.
CREATE TEMP TABLE programme_content_generated_shard_${shard} ON COMMIT DROP AS
${profiles}, matched AS (
 SELECT p.id AS programme_id,
        COALESCE(NULLIF(BTRIM(p.name_zh), ''), NULLIF(BTRIM(p.name_en), ''), p.programme_code) AS programme_name_zh,
        cp.*
 FROM programmes p
 JOIN subject_categories c ON c.id = p.subject_category_id
 CROSS JOIN LATERAL (
   SELECT profile.* FROM content_profiles profile
   WHERE (profile.category_code IS NULL OR profile.category_code = c.code)
     AND CONCAT_WS(' ', p.name_zh, p.name_en) ~* profile.name_pattern
   ORDER BY profile.priority
   LIMIT 1
 ) cp
 WHERE p.status = 'PUBLISHED' AND MOD(p.id, 4) = ${shard}
), entries AS (
 SELECT programme_id, programme_name_zh, 'CAREER_OPPORTUNITIES'::varchar AS section_type,
   '专业前景'::varchar AS title_zh, 'Career opportunities'::varchar AS title_en,
   programme_name_zh || '的行业应用：' || applications_zh || E'。\\n\\n具体就业岗位：' || roles_zh ||
     E'。\\n\\n核心能力：' || abilities_zh || E'。\\n\\n深造方向：' || further_zh ||
     E'。\\n\\n内容来源：根据专业名称和学科方向整理的一般性职业建议（AI 辅助），不是院校官方就业承诺。岗位准入和发展取决于个人能力、实习经历、当地法规及专业认证要求。' AS body_zh,
   'AI-generated general career guidance for this discipline; not an institutional employment claim.'::text AS body_en,
   30 AS sort_order
 FROM matched
 UNION ALL
 SELECT programme_id, programme_name_zh, 'CURRICULUM', '专业课程', 'Programme curriculum',
   '参考学习领域，非官方课程表（' || programme_name_zh || E'）\\n' ||
   '01|' || course_1_zh || '|' || course_1_en || E'\\n' ||
   '02|' || course_2_zh || '|' || course_2_en || E'\\n' ||
   '03|' || course_3_zh || '|' || course_3_en || E'\\n' ||
   '04|' || course_4_zh || '|' || course_4_en || E'\\n' ||
   '05|' || course_5_zh || '|' || course_5_en || E'\\n' ||
   '06|' || course_6_zh || '|' || course_6_en || E'\\n' ||
   '说明：以上是根据专业名称与学科方向生成的通用学习内容（AI 辅助），不是该院校已确认的课程名称、学分、必修或选修安排；请以院校最新官方教学大纲为准。',
   E'Illustrative study areas, not an official module list\\n' ||
   '01|' || course_1_en || '|' || course_1_zh || E'\\n' ||
   '02|' || course_2_en || '|' || course_2_zh || E'\\n' ||
   '03|' || course_3_en || '|' || course_3_zh || E'\\n' ||
   '04|' || course_4_en || '|' || course_4_zh || E'\\n' ||
   '05|' || course_5_en || '|' || course_5_zh || E'\\n' ||
   '06|' || course_6_en || '|' || course_6_zh || E'\\n' ||
   'Note: AI-generated general study areas. These are not verified institutional module names, credits or compulsory/elective requirements.',
   40
 FROM matched
)
SELECT * FROM entries;

INSERT INTO programme_detail_sections (
 programme_id, section_type, title_zh, title_en, body_zh, body_en,
 sort_order, source_url, source_checked_at, source_type, status, created_at, updated_at
)
SELECT programme_id, section_type, title_zh, title_en, body_zh, body_en,
       sort_order, NULL, NULL, 'ai_generated', 'PUBLISHED', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM programme_content_generated_shard_${shard}
ON CONFLICT (programme_id, section_type) DO UPDATE
SET title_zh = EXCLUDED.title_zh,
    title_en = EXCLUDED.title_en,
    body_zh = EXCLUDED.body_zh,
    body_en = EXCLUDED.body_en,
    sort_order = EXCLUDED.sort_order,
    source_url = NULL,
    source_checked_at = NULL,
    source_type = 'ai_generated',
    status = 'PUBLISHED',
    updated_at = CURRENT_TIMESTAMP
WHERE programme_detail_sections.source_type = 'ai_generated'
  AND (
    (EXCLUDED.section_type = 'CAREER_OPPORTUNITIES' AND (
      NULLIF(BTRIM(programme_detail_sections.body_zh), '') IS NULL
      OR programme_detail_sections.body_zh !~ '行业应用[：:]'
      OR programme_detail_sections.body_zh !~ '具体就业岗位[：:]'
      OR programme_detail_sections.body_zh !~ '核心能力[：:]'
      OR programme_detail_sections.body_zh !~ '深造方向[：:]'
      OR programme_detail_sections.body_zh ~* '(salary|employment rate|就业率|保证就业|年薪|月薪)'
    ))
    OR (EXCLUDED.section_type = 'CURRICULUM' AND (
      NULLIF(BTRIM(programme_detail_sections.body_zh), '') IS NULL
      OR programme_detail_sections.body_zh NOT LIKE '参考学习领域，非官方课程表%'
      OR programme_detail_sections.body_zh !~ '(?m)^01[|][^|]+[|][^|]+$'
      OR programme_detail_sections.body_zh !~ '(?m)^06[|][^|]+[|][^|]+$'
      OR programme_detail_sections.body_zh ~* '(entry requirements?|minimum (average|score|cgpa|grade)|ielts|toefl|muet|学费|录取要求)'
    ))
  );

-- Sourced career rows may intentionally retain official English job titles.
-- Add Chinese framing without translating or replacing the source text.
UPDATE programme_detail_sections section
SET title_zh = '专业前景',
    body_zh = CASE section.source_type
      WHEN 'official' THEN
        '就业方向：学校官网列出了与' || target.programme_name_zh || E'相关的职业方向。\\n\\n' ||
        '官网英文岗位名称：' || section.body_en || E'\\n\\n' ||
        '说明：以上英文岗位名称按官网原文保留，便于核对；岗位准入及发展要求以当地法规、专业认证和用人单位要求为准。'
      ELSE
        '就业方向：现有来源列出了与' || target.programme_name_zh || E'相关的职业方向。\\n\\n' ||
        '来源英文岗位名称：' || section.body_en || E'\\n\\n' ||
        '说明：以上英文岗位名称按原始资料保留，便于核对；具体要求请以来源页面和用人单位说明为准。'
    END,
    updated_at = CURRENT_TIMESTAMP
FROM (
  SELECT DISTINCT programme_id, programme_name_zh
  FROM programme_content_generated_shard_${shard}
) target
WHERE section.programme_id = target.programme_id
  AND section.section_type = 'CAREER_OPPORTUNITIES'
  AND section.source_type IN ('official', 'third_party')
  AND NULLIF(BTRIM(section.body_en), '') IS NOT NULL
  AND (NULLIF(BTRIM(section.body_zh), '') IS NULL OR section.body_zh !~ '[一-龥]');

-- V36 archived correctly labelled AI curricula solely because they had no
-- official URL. Republish valid generated rows without rewriting their text.
UPDATE programme_detail_sections section
SET title_zh = COALESCE(NULLIF(BTRIM(section.title_zh), ''),
      CASE section.section_type WHEN 'CURRICULUM' THEN '专业课程' ELSE '专业前景' END),
    status = 'PUBLISHED',
    updated_at = CURRENT_TIMESTAMP
FROM (
  SELECT DISTINCT programme_id FROM programme_content_generated_shard_${shard}
) target
WHERE section.programme_id = target.programme_id
  AND section.source_type = 'ai_generated'
  AND (
    (section.section_type = 'CAREER_OPPORTUNITIES'
      AND section.body_zh ~ '行业应用[：:]'
      AND section.body_zh ~ '具体就业岗位[：:]'
      AND section.body_zh ~ '核心能力[：:]'
      AND section.body_zh ~ '深造方向[：:]')
    OR (section.section_type = 'CURRICULUM'
      AND section.body_zh LIKE '参考学习领域，非官方课程表%'
      AND section.body_zh ~ '(?m)^01[|][^|]+[|][^|]+$'
      AND section.body_zh ~ '(?m)^06[|][^|]+[|][^|]+$')
  );

DO $$
BEGIN
 IF EXISTS (
   SELECT 1 FROM programmes p
   WHERE p.status = 'PUBLISHED' AND MOD(p.id, 4) = ${shard}
     AND NOT EXISTS (
       SELECT 1 FROM programme_detail_sections s
       WHERE s.programme_id = p.id AND s.section_type = 'CAREER_OPPORTUNITIES'
         AND s.status = 'PUBLISHED' AND NULLIF(BTRIM(s.body_zh), '') IS NOT NULL
         AND s.source_type IN ('official', 'third_party', 'ai_generated')
     )
 ) THEN RAISE EXCEPTION 'Shard ${shard}: published programme career coverage is incomplete'; END IF;
 IF EXISTS (
   SELECT 1 FROM programmes p
   WHERE p.status = 'PUBLISHED' AND MOD(p.id, 4) = ${shard}
     AND NOT EXISTS (
       SELECT 1 FROM programme_detail_sections s
       WHERE s.programme_id = p.id AND s.section_type = 'CURRICULUM'
         AND s.status = 'PUBLISHED' AND NULLIF(BTRIM(COALESCE(s.body_zh, s.body_en)), '') IS NOT NULL
         AND s.source_type IN ('official', 'third_party', 'ai_generated')
         AND (s.source_type <> 'ai_generated' OR s.body_zh LIKE '参考学习领域，非官方课程表%')
     )
 ) THEN RAISE EXCEPTION 'Shard ${shard}: published programme curriculum coverage is incomplete'; END IF;
 IF EXISTS (
   SELECT 1 FROM programme_detail_sections s
   JOIN programmes p ON p.id = s.programme_id
   WHERE p.status = 'PUBLISHED' AND MOD(p.id, 4) = ${shard}
     AND s.section_type IN ('CAREER_OPPORTUNITIES', 'CURRICULUM')
     AND s.source_type IN ('official', 'third_party')
     AND NULLIF(BTRIM(s.source_url), '') IS NULL
 ) THEN RAISE EXCEPTION 'Shard ${shard}: sourced content is missing its source URL'; END IF;
END $$;
`;

const output = resolve(root, `backend/src/main/resources/db/migration/V${version}__audit_programme_career_curriculum_shard_${shard}.sql`);
writeFileSync(output, sql, 'utf8');
console.log(`Wrote ${output}`);

